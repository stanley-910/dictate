import AppKit
import Foundation

/// The spoken "paste" command and the clipboard history it pastes from.
/// macOS keeps no history anyone can read, so the daemon keeps its own from
/// launch: the last `limit` plain-text copies, in memory only. Items a
/// password manager marks concealed or transient are skipped, and so are
/// dictate's own writes (the transcript it pastes, the clipboard it puts
/// back). Logs give counts, never contents.
final class ClipboardHistory {
    static let shared = ClipboardHistory()
    static let limit = 20
    /// Marks a spoken "paste" through post-processing, which leaves it alone.
    static let marker = "\u{E000}"
    /// What a "paste" command reads as in post-processed text: saved
    /// transcripts, `dictate fix`, and wherever there is no history.
    static let placeholder = "[paste]"

    /// `pasteOrder`: "recent" pastes the newest copy first, "oldest" the
    /// oldest of as many recent copies as there are commands.
    enum Order: String, Codable { case recent, oldest }

    /// Newest first.
    private(set) var items: [String] = []
    private var seen = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Polls the pasteboard on the main run loop; a change count read is cheap.
    func start() {
        seen = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
    }

    private static let skipped: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    /// Takes in what was copied since the last look.
    func check() {
        let pb = NSPasteboard.general
        guard timer != nil, pb.changeCount != seen else { return }
        seen = pb.changeCount
        let types = Set(pb.types ?? [])
        guard types.isDisjoint(with: Self.skipped), let text = pb.string(forType: .string), !text.isEmpty,
              items.first != text else { return }
        items.insert(text, at: 0)
        if items.count > Self.limit { items.removeLast() }
    }

    /// Clears the pasteboard for one of dictate's own writes, which then
    /// never enters the history; a copy made just before it is taken first.
    /// Only clearing moves the change count, so writing after it is safe.
    static func clearForOwnWrite(_ pb: NSPasteboard) {
        shared.check()
        pb.clearContents()
        if pb == NSPasteboard.general { shared.seen = pb.changeCount }
    }

    /// `text` with each placeholder replaced by a copy from the history.
    func fill(_ text: String, order: Order) -> String {
        check()
        let count = text.components(separatedBy: Self.placeholder).count - 1
        guard count > 0 else { return text }
        log("paste: \(count) command(s), \(items.count) item(s) in history")
        return Self.fill(text, history: items, order: order)
    }

    /// The pure part of `fill`: `history` is newest first. With fewer copies
    /// than commands, the extra commands insert nothing.
    static func fill(_ text: String, history: [String], order: Order) -> String {
        let parts = text.components(separatedBy: placeholder)
        let count = parts.count - 1
        guard count > 0 else { return text }
        var picks = Array(history.prefix(count))
        if order == .oldest { picks.reverse() }
        var out = parts[0]
        for (k, part) in parts.dropFirst().enumerated() {
            if k < picks.count {
                out += picks[k] + part
            } else if out.hasSuffix(" "), part.hasPrefix(" ") || part.isEmpty {
                // Nothing to insert: drop the space it would have sat between.
                out.removeLast()
                out += part
            } else {
                out += part.hasPrefix(" ") && (out.isEmpty || out.hasSuffix("\n")) ? String(part.dropFirst()) : part
            }
        }
        return out
    }

    // MARK: the spoken command

    /// Turns each spoken "paste" command into `marker`. A command stands
    /// apart: punctuation, the start or end, or a spoken "new line" on each
    /// side ("Here is the error. Paste. And", "speaking, new line, paste,
    /// new line"). "copy and paste it", "paste the link below" and "this
    /// paste with" stay words. A comma before it and its own punctuation go,
    /// since the copy is inserted as it was.
    static func mark(_ text: String) -> String {
        var words = text.split(separator: " ", omittingEmptySubsequences: false).map(String.init)
        let bare = { (w: String) in w.lowercased().trimmingCharacters(in: .punctuationCharacters) }
        let breaks: Set<String> = ["line", "newline", "paragraph"]
        var found = false
        for i in words.indices where bare(words[i]) == "paste" {
            let w = words[i]
            guard w.first?.isLetter == true else { continue }
            let leftOpen = i == 0 || words[i - 1].last.map { !$0.isLetter && !$0.isNumber } == true
                || breaks.contains(bare(words[i - 1]))
            let rightOpen = w.last?.isLetter != true || i + 1 == words.count
                || (bare(words[i + 1]) == "new" || bare(words[i + 1]) == "newline")
            guard leftOpen, rightOpen else { continue }
            if i > 0, words[i - 1].hasSuffix(",") { words[i - 1].removeLast() }
            words[i] = marker
            found = true
        }
        return found ? words.joined(separator: " ") : text
    }
}
