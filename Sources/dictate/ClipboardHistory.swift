import AppKit
import Foundation

/// The spoken "paste" command and the clipboard history it pastes from.
/// macOS keeps no history anyone can read, so the daemon keeps its own from
/// launch: the last `limit` copies (text, images, files), in memory only. Items a
/// password manager marks concealed or transient are skipped, and so are
/// dictate's own writes (the transcript it pastes, the clipboard it puts
/// back). Logs give counts, never contents.
final class ClipboardHistory {
    static let shared = ClipboardHistory()
    static let limit = 20
    /// Marks a spoken "paste" through post-processing, which leaves it alone.
    static let marker = "\u{E000}"
    /// What a "paste" command reads as in post-processed text: saved
    /// transcripts, `dictate fix`, and wherever there is no history.
    static let placeholder = "[paste]"

    /// `pasteOrder`: "recent" pastes the newest copy first, "oldest" the
    /// oldest of as many recent copies as there are commands.
    enum Order: String, Codable { case recent, oldest }

    /// One copy: plain text, or everything on the pasteboard for an image
    /// or a file, put back as it was to be pasted.
    enum Item: Equatable {
        case text(String)
        case rich(PasteSnapshot)
    }

    /// Copies bigger than this are not kept (a 5K screenshot is about 30 MB).
    static let maxBytes = 64 << 20
    private static let richTypes: Set<NSPasteboard.PasteboardType> = [
        .png, .tiff, .fileURL, .init("public.jpeg"), .init("public.heic"), .init("com.compuserve.gif"), .pdf,
    ]

    /// Newest first.
    private(set) var items: [Item] = []
    /// Pastes the user made by hand during the recording in progress, since
    /// the newest copy: each one moves that recording's spoken "paste" a
    /// copy down, as that copy is already in place.
    private(set) var pastedByHand = 0

    init(items: [Item] = []) { self.items = items }

    /// The user pressed Cmd-V (or Ctrl-V in a terminal).
    func pastedByUser() {
        check()
        pastedByHand += 1
    }

    /// The count so far, starting over: called when a recording starts
    /// (dropping what came before it) and when it stops (for its delivery).
    func takePastedByHand() -> Int {
        defer { pastedByHand = 0 }
        return pastedByHand
    }

    /// The copies a spoken "paste" draws on, newest first, for a recording
    /// with `pasted` pastes by hand in it.
    func remaining(after pasted: Int) -> [Item] { Array(items.dropFirst(pasted)) }
    private var seen = NSPasteboard.general.changeCount
    private var timer: Timer?

    /// Polls the pasteboard on the main run loop; a change count read is cheap.
    func start() {
        seen = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.check() }
    }

    private static let skipped: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    // An image is read off the main thread: a large one takes long enough
    // to hold up the hotkey. `read` is what came back; `reading` says one is
    // on its way.
    private let reader = DispatchQueue(label: "dictate.clipboard", qos: .utility)
    private let lock = NSLock()
    private var read: [Item] = []
    private var reading = 0

    /// Takes in what was copied since the last look. `wait` holds on for an
    /// image still being read, for callers that need the history complete now.
    func check(wait: Bool = false) {
        let pb = NSPasteboard.general
        let changed = timer != nil && pb.changeCount != seen
        // An image still being read is older than whatever comes next.
        if wait || changed { lock.lock(); let busy = reading > 0; lock.unlock(); if busy { reader.sync {} } }
        takeRead()
        guard changed else { return }
        let count = pb.changeCount
        seen = count
        let types = Set(pb.types ?? [])
        guard types.isDisjoint(with: Self.skipped) else { return }
        if !types.isDisjoint(with: Self.richTypes) {
            pastedByHand = 0
            lock.lock(); reading += 1; lock.unlock()
            let work = { [self] in
                defer { lock.lock(); reading -= 1; lock.unlock() }
                let t0 = Date()
                let snap = Paster.snapshot(pb)
                let bytes = snap.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } }
                let ms = Int(Date().timeIntervalSince(t0) * 1000)
                if ms >= 50 { log("reading a copied image or file of \(bytes >> 20) MB took \(ms) ms") }
                // A copy made while reading leaves this one half old, half new.
                log("copied: image or file, \(bytes >> 10) KB in \(snap.first?.count ?? 0) format(s), change \(count)\(pb.changeCount == count ? "" : "; replaced while reading, dropped")")
                guard bytes > 0, bytes <= Self.maxBytes, pb.changeCount == count else { return }
                lock.lock(); read.append(.rich(snap)); lock.unlock()
            }
            if wait {
                reader.sync(execute: work)
                takeRead()
            } else {
                reader.async {
                    work()
                    DispatchQueue.main.async { self.takeRead() }
                }
            }
        } else if let text = pb.string(forType: .string), !text.isEmpty {
            pastedByHand = 0
            log("copied: text, \(text.count) characters, change \(count)")
            add(.text(text))
        }
    }

    private func takeRead() {
        lock.lock()
        let done = read
        read = []
        lock.unlock()
        done.forEach(add)
    }

    private func add(_ item: Item) {
        guard items.first != item else { return }
        items.insert(item, at: 0)
        if items.count > Self.limit { items.removeLast() }
    }

    /// Clears the pasteboard for one of dictate's own writes, which then
    /// never enters the history; a copy made just before it is taken first.
    /// Only clearing moves the change count, so writing after it is safe.
    static func clearForOwnWrite(_ pb: NSPasteboard) {
        shared.check(wait: true)
        pb.clearContents()
        if pb == NSPasteboard.general { shared.seen = pb.changeCount }
    }

    /// What to paste, in order: text, and images or files between it.
    enum Part: Equatable {
        case text(String)
        case rich(PasteSnapshot)
    }

    /// `text` with each placeholder replaced by a copy from the history.
    func fill(_ text: String, order: Order, pastedByHand: Int = 0) -> [Part] {
        check(wait: true)
        let count = text.components(separatedBy: Self.placeholder).count - 1
        guard count > 0 else { return text.isEmpty ? [] : [.text(text)] }
        let items = remaining(after: pastedByHand)
        let kinds = items.prefix(count).map { if case .text = $0 { return "text" } else { return "image or file" } }
        log("paste: \(count) command(s), \(items.count) item(s) in history after \(pastedByHand) pasted by hand; newest first: \(kinds.joined(separator: ", "))")
        return Self.fill(text, history: items, order: order)
    }

    /// The text of `parts` alone, for the clipboard, which holds one thing.
    static func text(_ parts: [Part]) -> String {
        parts.map { if case .text(let s) = $0 { return s } else { return "" } }.joined()
    }

    /// Text-only history, as one string.
    static func fill(_ text: String, history: [String], order: Order) -> String {
        Self.text(fill(text, history: history.map(Item.text), order: order))
    }

    /// The pure part of `fill`: `history` is newest first. With fewer copies
    /// than commands, the extra commands insert nothing. An image or file
    /// splits the text around it into separate pastes.
    static func fill(_ text: String, history: [Item], order: Order) -> [Part] {
        let parts = text.components(separatedBy: placeholder)
        let count = parts.count - 1
        var picks = Array(history.prefix(count))
        if order == .oldest { picks.reverse() }
        var done: [Part] = []
        var out = parts[0]
        for (k, part) in parts.dropFirst().enumerated() {
            if k < picks.count {
                switch picks[k] {
                case .text(let copy):
                    out += copy + part
                case .rich(let snap):
                    if !out.isEmpty { done.append(.text(out)) }
                    done.append(.rich(snap))
                    out = part
                }
            } else if out.hasSuffix(" "), part.hasPrefix(" ") || part.isEmpty {
                // Nothing to insert: drop the space it would have sat between.
                out.removeLast()
                out += part
            } else {
                out += part.hasPrefix(" ") && (out.isEmpty || out.hasSuffix("\n")) ? String(part.dropFirst()) : part
            }
        }
        if !out.isEmpty { done.append(.text(out)) }
        return done
    }

    // MARK: the spoken command

    /// Turns each spoken "paste" command into `marker`. A command stands
    /// apart: punctuation, the start or end, or a spoken "new line" on each
    /// side ("Here is the error. Paste. And", "speaking, new line, paste,
    /// new line"). "copy and paste it", "paste the link below" and "this
    /// paste with" stay words. A comma before it and its own punctuation go,
    /// since the copy is inserted as it was.
    static func mark(_ text: String) -> String {
        var words = text.split(separator: " ", omittingEmptySubsequences: false).map(String.init)
        let bare = { (w: String) in w.lowercased().trimmingCharacters(in: .punctuationCharacters) }
        let breaks: Set<String> = ["line", "newline", "paragraph"]
        var found = false
        for i in words.indices where bare(words[i]) == "paste" {
            let w = words[i]
            guard w.first?.isLetter == true else { continue }
            let leftOpen = i == 0 || words[i - 1].last.map { !$0.isLetter && !$0.isNumber } == true
                || breaks.contains(bare(words[i - 1]))
            let rightOpen = w.last?.isLetter != true || i + 1 == words.count
                || (bare(words[i + 1]) == "new" || bare(words[i + 1]) == "newline")
            guard leftOpen, rightOpen else { continue }
            if i > 0, words[i - 1].hasSuffix(",") { words[i - 1].removeLast() }
            words[i] = marker
            found = true
        }
        return found ? words.joined(separator: " ") : text
    }
}
